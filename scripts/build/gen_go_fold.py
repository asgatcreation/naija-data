"""Generate go/fold_table.go: how each accented or compatibility character folds to ASCII.

Python and JavaScript use Unicode NFKD decomposition and then drop non-ASCII characters. Go's
standard library has no NFKD, and the Go module must have no dependencies, so we precompute the
same result for the character ranges that matter (Latin, Latin Extended, Yoruba/Hausa letters with
dots and tones, Vietnamese-style extended Latin, ligatures, full-width forms). Characters outside the
table are dropped in all three languages, and the parity tests check accented input.

Run:  python scripts/build/gen_go_fold.py
"""

from __future__ import annotations

import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "go" / "fold_table.go"

RANGES = [(0x00A0, 0x024F), (0x1E00, 0x1EFF), (0x2000, 0x2BFF), (0xFB00, 0xFB06), (0xFF01, 0xFF5E)]


def main() -> None:
    entries = []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            folded = unicodedata.normalize("NFKD", chr(cp)).encode("ascii", "ignore").decode()
            if folded:
                entries.append((cp, folded))
    lines = [
        "// Code generated by scripts/build/gen_go_fold.py from Unicode NFKD data. DO NOT EDIT.",
        "",
        "package naija",
        "",
        "// foldTable maps characters to the ASCII text Unicode NFKD decomposition leaves after dropping",
        "// non-ASCII parts (e.g. 'ọ' -> \"o\", 'ﬁ' -> \"fi\"). Characters not listed fold to nothing.",
        f"// Unicode version: {unicodedata.unidata_version}.",
        "var foldTable = map[rune]string{",
    ]
    for cp, folded in entries:
        lines.append(f"\t0x{cp:04X}: {go_string(folded)},")
    lines += ["}", ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(entries)} entries -> {OUT.relative_to(ROOT)}")


def go_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    main()
